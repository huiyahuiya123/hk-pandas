/* header shadow + tapbar active */
const header = $('#siteHeader');
window.addEventListener('scroll', () => header.classList.toggle('scrolled', window.scrollY > 8), {passive:true});
const tapLinks = $$('.tapbar a');
const sections = ['family','members','daily','timeline','visit'].map(id => document.getElementById(id));
window.addEventListener('scroll', () => {
  let active = 0;
  sections.forEach((sec,i) => { if(sec && sec.getBoundingClientRect().top < window.innerHeight * 0.45) active = i; });
  tapLinks.forEach((a,i) => a.classList.toggle('active', i === active));
}, {passive:true});

/* reveal on scroll */
const io = new IntersectionObserver(entries => {
  entries.forEach(en => { if(en.isIntersecting){ en.target.classList.add('in'); io.unobserve(en.target); } });
}, {threshold: .12});
$$('.reveal').forEach(el => io.observe(el));

/* language switch */
$$('.lang-switch button').forEach(btn => {
  btn.addEventListener('click', () => {
    LANG = btn.dataset.lang;
    $$('.lang-switch button').forEach(b => b.classList.toggle('active', b === btn));
    applyI18n(); renderMembers();
  });
});

applyI18n(); renderMembers(); updateDailyNav();
