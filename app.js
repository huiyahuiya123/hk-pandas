let LANG = 'zh';

function t(key){ return (I18N[LANG] && I18N[LANG][key]) || I18N.zh[key] || key; }

function applyI18n(){
  $$('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  $$('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.documentElement.lang = LANG === 'hk' ? 'zh-HK' : (LANG === 'en' ? 'en' : 'zh-CN');
  document.title = LANG === 'en' ? 'Panda Family · Ocean Park Hong Kong' : (LANG === 'hk' ? '大熊貓之家 · 香港海洋公園' : '大熊猫之家 · 香港海洋公园');
}

